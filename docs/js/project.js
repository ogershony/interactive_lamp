/**
 * The physical invariants, ported line-for-line from the Python.
 *
 *   easeTrack   <- data/lamp_retargeting/filters.py::ease_track
 *   project     <- motion_generator/sample.py::project
 *   denormalize <- motion_generator/sample.py::denormalize
 *
 * This is not decoration. Raw model output exceeds the 1.8 rad/s rate cap on
 * a minority of frames, which fails the validator outright; re-applying the
 * cap took the validator from 0/8 to 8/8 at cfg 2.5 while retaining 99% of
 * mean speed. Guidance above 1 is only safe because this runs after it.
 *
 * docs/tests/project.test.mjs checks this port against fixtures generated by
 * the Python, so the browser cannot quietly diverge from the robot.
 */

export const INV = {
  dt: 0.033,
  rateCap: 1.8,        // rad/s
  accelCap: 15.0,      // rad/s^2
  brakeMult: 2.0,
  lightSlew: 0.8,      // per second
};

/**
 * Causal accel + velocity limited tracking: ease-in/ease-out S-curves rather
 * than the hard corners of a plain rate limiter. Identity for motion that
 * already respects the caps.
 */
export function easeTrack(x, {
  vcap = INV.rateCap, acap = INV.accelCap, dt = INV.dt,
} = {}) {
  const n = x.length;
  const out = new Float64Array(n);
  if (n === 0) return out;
  const brake = INV.brakeMult * acap;
  out[0] = x[0];
  let p = x[0], v = 0.0;
  for (let i = 1; i < n; i++) {
    const err = x[i] - p;
    const half = (brake * dt) / 2.0;
    // highest speed from which the tracker can still stop on target in
    // discrete decel steps; the naive sqrt(2A|err|) form chatters at 30 Hz
    const vStop = -half + Math.sqrt(half * half + 2.0 * brake * Math.abs(err));
    const mag = Math.min(vcap, vStop);
    const vDes = err < 0 ? -mag : mag;
    const vLand = err / dt;
    if (Math.abs(vLand) <= Math.abs(vDes)
        && Math.abs(vLand - v) <= brake * dt) {
      // landing exactly on this input sample stays inside the braking
      // envelope: follow it (bitwise identity for trackable motion)
      v = vLand;
      p = x[i];
    } else {
      const lim = (v * err < 0 || Math.abs(vDes) < Math.abs(v)) ? brake : acap;
      v = Math.min(Math.max(vDes, v - lim * dt), v + lim * dt);
      v = Math.min(Math.max(v, -vcap), vcap);
      p += v * dt;
    }
    out[i] = p;
  }
  return out;
}

/** Causal slew clamp on the LED, the light half of the same contract. */
export function slewLight(light, dt = INV.dt) {
  const n = light.length;
  const out = new Float64Array(n);
  if (n === 0) return out;
  const step = INV.lightSlew * dt;
  out[0] = Math.min(1, Math.max(0, light[0]));
  for (let i = 1; i < n; i++) {
    const target = Math.min(1, Math.max(0, light[i]));
    const d = Math.min(step, Math.max(-step, target - out[i - 1]));
    out[i] = out[i - 1] + d;
  }
  return out;
}

/**
 * Re-apply the mapping's output invariants to a sampled clip.
 *
 * Deliberately no lowpass prefilter: the model learned from post-lowpass
 * data, so a second pass only removes motion (measured: lowpass+easeTrack
 * keeps 84% of mean speed, easeTrack alone keeps 99%, both at zero validator
 * failures). Keeping the motion is the point.
 *
 * `frames` is a T x 9 array of arrays. Returns {frames, trimmed} where
 * trimmed counts frames the projection actually had to move -- the site
 * shows it so the invariant is visible rather than asserted.
 */
export function project(frames) {
  const T = frames.length;
  if (!T) return { frames, trimmed: 0 };
  const out = frames.map((f) => f.slice());

  for (let j = 0; j < 5; j++) {
    const col = new Float64Array(T);
    for (let i = 0; i < T; i++) col[i] = frames[i][j];
    const eased = easeTrack(col);
    for (let i = 0; i < T; i++) out[i][j] = eased[i];
  }

  const light = new Float64Array(T);
  for (let i = 0; i < T; i++) light[i] = frames[i][5];
  const slewed = slewLight(light);
  for (let i = 0; i < T; i++) out[i][5] = slewed[i];

  let trimmed = 0;
  for (let i = 0; i < T; i++) {
    let moved = Math.abs(out[i][5] - frames[i][5]) > 1e-6;
    for (let j = 0; j < 5 && !moved; j++) {
      if (Math.abs(out[i][j] - frames[i][j]) > 1e-6) moved = true;
    }
    if (moved) trimmed++;
  }
  return { frames: out, trimmed };
}

/** Undo the training normalization and clamp to the train-data envelope. */
export function denormalize(flat, T, stats) {
  const { mean, std, lo, hi } = stats;
  const C = mean.length;
  const out = [];
  for (let i = 0; i < T; i++) {
    const row = new Array(C);
    for (let c = 0; c < C; c++) {
      const v = flat[i * C + c] * std[c] + mean[c];
      row[c] = Math.min(hi[c], Math.max(lo[c], v));
    }
    out.push(row);
  }
  return out;
}

/** Peak |dq|/dt over a clip, in rad/s -- the number the rate cap bounds. */
export function peakRate(frames, dt = INV.dt) {
  let peak = 0;
  for (let i = 1; i < frames.length; i++) {
    for (let j = 0; j < 5; j++) {
      const r = Math.abs(frames[i][j] - frames[i - 1][j]) / dt;
      if (r > peak) peak = r;
    }
  }
  return peak;
}

/** Mean joint speed, the statistic the projection is tuned to preserve. */
export function meanSpeed(frames, dt = INV.dt) {
  if (frames.length < 2) return 0;
  let s = 0;
  for (let i = 1; i < frames.length; i++) {
    for (let j = 0; j < 5; j++) {
      s += Math.abs(frames[i][j] - frames[i - 1][j]) / dt;
    }
  }
  return s / (5 * (frames.length - 1));
}
